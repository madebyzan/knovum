import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";

import { inspectSourceLayout } from "../source-layout.mjs";

function fixture(t, files, directories = []) {
  const root = mkdtempSync(join(tmpdir(), "knovum-source-layout-"));
  t.after(() => rmSync(root, { recursive: true }));
  for (const directory of directories) mkdirSync(join(root, directory), { recursive: true });
  for (const [name, source] of Object.entries(files)) {
    mkdirSync(join(root, name, ".."), { recursive: true });
    writeFileSync(join(root, name), source);
  }
  return root;
}

test("sibling stems conflict across supported platform case conventions", (t) => {
  const root = fixture(t, { "Worker.py": "pass\n" }, ["worker"]);
  assert.match(inspectSourceLayout(root)[0], /conflicts with directory/);
});

test("embedded tests are rejected in Rust, Python and frontend business sources", (t) => {
  const root = fixture(t, {
    "publication.rs": "#[cfg(test)]\nmod tests {\n#[test]\nfn commits() {}\n}\n",
    "worker.py": "def test_worker(): pass\n",
    "view.ts": 'import { test } from "vitest";\n',
    "catalog.test.ts": "export {};\n",
  });
  assert.equal(inspectSourceLayout(root).length, 4);
});

test("native test modules and dedicated test directories are accepted", (t) => {
  const root = fixture(t, {
    "publication/mod.rs": "#[cfg(test)]\nmod tests;\n",
    "publication/tests/mod.rs": "#[test]\nfn commits() {}\n",
    "__tests__/view.test.ts": 'import { test } from "vitest";\n',
    "tests/test_worker.py": "def test_worker(): pass\n",
  });
  assert.deepEqual(inspectSourceLayout(root), []);
});

test("size policy caps handwritten and generated files by nonblank lines", (t) => {
  const root = fixture(t, {
    "worker.py": "pass\n\n".repeat(351),
    "boundary.rs": "const A: u8 = 1;\n\n".repeat(350),
    "contracts.py": "# generated by datamodel-codegen:\n" + "pass\n".repeat(500),
  });
  const violations = inspectSourceLayout(root);
  assert.equal(violations.length, 2);
  assert.ok(violations.some((message) => /351 nonblank lines/.test(message)));
  assert.ok(violations.some((message) => /501 nonblank lines/.test(message)));
});

test("Vue size includes template and style, rather than only script", (t) => {
  const root = fixture(t, {
    "Dialog.vue":
      '<script setup lang="ts">\nconst open = true;\n</script>\n<template>\n' +
      "  <span>value</span>\n".repeat(180) +
      "</template>\n",
    "Small.vue": "<template>\n<div />\n</template>\n",
  });
  const violations = inspectSourceLayout(root);
  assert.equal(violations.length, 1);
  assert.match(violations[0], /Dialog\.vue: 185 nonblank lines exceeds the 180-line/);
});
