/** Release policy. Public configuration is embedded before Tauri initializes plugins. */
export function requireValue(value, name) {
  if (typeof value !== "string" || !value.trim()) throw new Error(`${name} is required`);
  return value.trim();
}

export function httpsUrl(value, name) {
  const text = requireValue(value, name);
  let url;
  try {
    url = new URL(text);
  } catch {
    throw new Error(`${name} must be an absolute HTTPS URL`);
  }
  if (url.protocol !== "https:" || url.username || url.password || url.hash || url.search) {
    throw new Error(`${name} must use HTTPS without credentials, query parameters, or a fragment`);
  }
  if (text.includes("{{") || text.includes("}}")) {
    throw new Error(`${name} must identify a static update manifest, not a URL template`);
  }
  return url.href;
}

export function decodeBase64(value, name) {
  const text = requireValue(value, name);
  const bytes = Buffer.from(text, "base64");
  if (!bytes.length || bytes.toString("base64") !== text) {
    throw new Error(`${name} must contain canonical base64`);
  }
  return bytes;
}

export function publicKey(value) {
  const encoded = requireValue(value, "KNOVUM_UPDATER_PUBKEY");
  const lines = decodeBase64(encoded, "KNOVUM_UPDATER_PUBKEY").toString("utf8").trimEnd().split(/\r?\n/);
  if (lines.length !== 2 || !lines[0].startsWith("untrusted comment:")) {
    throw new Error("KNOVUM_UPDATER_PUBKEY must be the public key generated by Tauri signer");
  }
  const key = decodeBase64(lines[1], "minisign public key");
  if (key.length !== 42 || key.subarray(0, 2).toString("ascii") !== "Ed") {
    throw new Error("KNOVUM_UPDATER_PUBKEY has an invalid minisign public-key envelope");
  }
  return { encoded, minisign: lines[1] };
}

export function stableVersion(value) {
  const version = requireValue(value, "release version");
  if (!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version)) {
    throw new Error("The stable channel requires a plain MAJOR.MINOR.PATCH version");
  }
  return version;
}

export function releaseConfiguration(environment) {
  if (environment.TAURI_CONFIG?.trim()) {
    throw new Error("Release packaging does not permit an inherited TAURI_CONFIG override");
  }
  const endpoint = httpsUrl(environment.KNOVUM_UPDATER_ENDPOINT, "KNOVUM_UPDATER_ENDPOINT");
  const { encoded } = publicKey(environment.KNOVUM_UPDATER_PUBKEY);
  requireValue(environment.TAURI_SIGNING_PRIVATE_KEY, "TAURI_SIGNING_PRIVATE_KEY");
  return {
    plugins: {
      updater: { endpoints: [endpoint], pubkey: encoded, windows: { installMode: "passive" } },
    },
  };
}

export function releaseRepository(value) {
  const repository = requireValue(value, "KNOVUM_RELEASE_REPOSITORY");
  if (
    !/^[A-Za-z0-9][A-Za-z0-9-]*\/[A-Za-z0-9_.-]+$/.test(repository) ||
    [".", ".."].includes(repository.split("/")[1])
  ) {
    throw new Error("KNOVUM_RELEASE_REPOSITORY must have owner/repository form");
  }
  return repository;
}

export function validateReleaseArguments(args) {
  for (const argument of args) {
    if (
      ["--", "--debug", "-d", "--no-bundle", "--no-sign", "--skip-stapling"].includes(argument) ||
      argument === "--config" ||
      argument.startsWith("--config=") ||
      argument.startsWith("-c")
    ) {
      throw new Error(`Release packaging does not permit ${argument}`);
    }
  }
  const features = args.flatMap((argument, index) => {
    if (argument === "--features" || argument === "-f") return [args[index + 1] ?? ""];
    if (argument.startsWith("-f") && argument !== "-f") return [argument.slice(2)];
    return argument.startsWith("--features=") ? [argument.slice("--features=".length)] : [];
  });
  if (features.some((value) => value.split(/[,\s]+/).includes("e2e"))) {
    throw new Error("Production releases must not include the e2e feature");
  }
}
