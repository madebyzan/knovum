pub(super) fn specific_fields_for_kind(kind: &str) -> Result<&'static [&'static str], String> {
    match kind {
        "note" | "text" => Ok(&["tiptapContent", "plainText"]),
        "markdown" => Ok(&["text", "derivationState"]),
        "website" => Ok(super::website::FIELDS),
        "image" => Ok(IMAGE_ASSET_FIELDS),
        "video" => Ok(VIDEO_ASSET_FIELDS),
        "audio" => Ok(MEDIA_ASSET_FIELDS),
        "subtitle" => Ok(&[
            "sourceVideoNodeId",
            "sourceVideoRevision",
            "language",
            "durationMs",
            "cues",
        ]),
        "file" => Ok(FILE_ASSET_FIELDS),
        "code" => Ok(CODE_ASSET_FIELDS),
        "credential" => Ok(&["credentialKind", "credentialConfigured"]),
        "object" => Ok(&["objectTypeId", "summary", "status", "properties"]),
        "portal" => Ok(&["targetSpaceId", "targetSceneId", "targetNodeId"]),
        "section" => Ok(&["collapsed"]),
        _ => Err("Unsupported Space node kind".into()),
    }
}
