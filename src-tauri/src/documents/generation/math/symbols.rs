#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) enum SymbolKind {
    Ident,
    Operator,
    Function,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) struct Symbol {
    pub unicode: &'static str,
    pub typst: &'static str,
    pub kind: SymbolKind,
}

const fn ident(unicode: &'static str, typst: &'static str) -> Symbol {
    Symbol {
        unicode,
        typst,
        kind: SymbolKind::Ident,
    }
}

const fn op(unicode: &'static str, typst: &'static str) -> Symbol {
    Symbol {
        unicode,
        typst,
        kind: SymbolKind::Operator,
    }
}

const fn func(unicode: &'static str, typst: &'static str) -> Symbol {
    Symbol {
        unicode,
        typst,
        kind: SymbolKind::Function,
    }
}

pub(super) fn lookup(name: &str) -> Option<Symbol> {
    Some(match name {
        // Lowercase Greek
        "alpha" => ident("α", "alpha"),
        "beta" => ident("β", "beta"),
        "gamma" => ident("γ", "gamma"),
        "delta" => ident("δ", "delta"),
        "epsilon" => ident("ϵ", "epsilon"),
        "varepsilon" => ident("ε", "epsilon.alt"),
        "zeta" => ident("ζ", "zeta"),
        "eta" => ident("η", "eta"),
        "theta" => ident("θ", "theta"),
        "vartheta" => ident("ϑ", "theta.alt"),
        "iota" => ident("ι", "iota"),
        "kappa" => ident("κ", "kappa"),
        "lambda" => ident("λ", "lambda"),
        "mu" => ident("μ", "mu"),
        "nu" => ident("ν", "nu"),
        "xi" => ident("ξ", "xi"),
        "pi" => ident("π", "pi"),
        "varpi" => ident("ϖ", "pi.alt"),
        "rho" => ident("ρ", "rho"),
        "varrho" => ident("ϱ", "rho.alt"),
        "sigma" => ident("σ", "sigma"),
        "varsigma" => ident("ς", "sigma.alt"),
        "tau" => ident("τ", "tau"),
        "upsilon" => ident("υ", "upsilon"),
        "phi" => ident("ϕ", "phi.alt"),
        "varphi" => ident("φ", "phi"),
        "chi" => ident("χ", "chi"),
        "psi" => ident("ψ", "psi"),
        "omega" => ident("ω", "omega"),
        // Uppercase Greek
        "Gamma" => ident("Γ", "Gamma"),
        "Delta" => ident("Δ", "Delta"),
        "Theta" => ident("Θ", "Theta"),
        "Lambda" => ident("Λ", "Lambda"),
        "Xi" => ident("Ξ", "Xi"),
        "Pi" => ident("Π", "Pi"),
        "Sigma" => ident("Σ", "Sigma"),
        "Upsilon" => ident("Υ", "Upsilon"),
        "Phi" => ident("Φ", "Phi"),
        "Psi" => ident("Ψ", "Psi"),
        "Omega" => ident("Ω", "Omega"),
        // Big operators
        "sum" => op("∑", "sum"),
        "prod" => op("∏", "product"),
        "coprod" => op("∐", "coprod"),
        "int" => op("∫", "integral"),
        "iint" => op("∬", "integral.double"),
        "iiint" => op("∭", "integral.triple"),
        "oint" => op("∮", "integral.cont"),
        "bigcup" => op("⋃", "union.big"),
        "bigcap" => op("⋂", "sect.big"),
        // Named functions
        "sin" => func("sin", "sin"),
        "cos" => func("cos", "cos"),
        "tan" => func("tan", "tan"),
        "cot" => func("cot", "cot"),
        "sec" => func("sec", "sec"),
        "csc" => func("csc", "csc"),
        "arcsin" => func("arcsin", "arcsin"),
        "arccos" => func("arccos", "arccos"),
        "arctan" => func("arctan", "arctan"),
        "sinh" => func("sinh", "sinh"),
        "cosh" => func("cosh", "cosh"),
        "tanh" => func("tanh", "tanh"),
        "log" => func("log", "log"),
        "ln" => func("ln", "ln"),
        "exp" => func("exp", "exp"),
        "lim" => func("lim", "lim"),
        "limsup" => func("lim sup", "limsup"),
        "liminf" => func("lim inf", "liminf"),
        "max" => func("max", "max"),
        "min" => func("min", "min"),
        "sup" => func("sup", "sup"),
        "inf" => func("inf", "inf"),
        "arg" => func("arg", "arg"),
        "det" => func("det", "det"),
        "dim" => func("dim", "dim"),
        "gcd" => func("gcd", "gcd"),
        "ker" => func("ker", "ker"),
        "Pr" => func("Pr", "Pr"),
        "mod" | "bmod" | "pmod" => func("mod", "mod"),
        // Relations & arrows
        "le" | "leq" => op("≤", "<="),
        "ge" | "geq" => op("≥", ">="),
        "ne" | "neq" => op("≠", "!="),
        "approx" => op("≈", "approx"),
        "equiv" => op("≡", "equiv"),
        "sim" => op("∼", "tilde.op"),
        "simeq" => op("≃", "tilde.eq"),
        "cong" => op("≅", "tilde.equiv"),
        "propto" => op("∝", "prop"),
        "ll" => op("≪", "lt.double"),
        "gg" => op("≫", "gt.double"),
        "in" => op("∈", "in"),
        "notin" => op("∉", "in.not"),
        "ni" => op("∋", "in.rev"),
        "subset" => op("⊂", "subset"),
        "subseteq" => op("⊆", "subset.eq"),
        "supset" => op("⊃", "supset"),
        "supseteq" => op("⊇", "supset.eq"),
        "to" | "rightarrow" => op("→", "->"),
        "leftarrow" | "gets" => op("←", "<-"),
        "leftrightarrow" => op("↔", "<->"),
        "Rightarrow" | "implies" => op("⇒", "=>"),
        "Leftarrow" => op("⇐", "arrow.l.double"),
        "Leftrightarrow" | "iff" => op("⇔", "<=>"),
        "mapsto" => op("↦", "|->"),
        "uparrow" => op("↑", "arrow.t"),
        "downarrow" => op("↓", "arrow.b"),
        // Binary operators & logic
        "times" => op("×", "times"),
        "cdot" => op("·", "dot.op"),
        "div" => op("÷", "div"),
        "pm" => op("±", "plus.minus"),
        "mp" => op("∓", "minus.plus"),
        "circ" => op("∘", "circle.tiny"),
        "bullet" => op("•", "bullet"),
        "oplus" => op("⊕", "plus.circle"),
        "otimes" => op("⊗", "times.circle"),
        "cup" => op("∪", "union"),
        "cap" => op("∩", "sect"),
        "setminus" => op("∖", "without"),
        "land" | "wedge" => op("∧", "and"),
        "lor" | "vee" => op("∨", "or"),
        "neg" | "lnot" => op("¬", "not"),
        "forall" => op("∀", "forall"),
        "exists" => op("∃", "exists"),
        "mid" | "vert" => op("|", "|"),
        "Vert" | "parallel" => op("‖", "bar.v.double"),
        // Constants, calculus & punctuation
        "infty" => ident("∞", "infinity"),
        "partial" => op("∂", "diff"),
        "nabla" => op("∇", "nabla"),
        "emptyset" | "varnothing" => ident("∅", "emptyset"),
        "dots" | "ldots" => op("…", "dots.h"),
        "cdots" => op("⋯", "dots.c"),
        "vdots" => op("⋮", "dots.v"),
        "ddots" => op("⋱", "dots.down"),
        "prime" => op("′", "'"),
        "degree" => op("°", "degree"),
        "angle" => op("∠", "angle"),
        "perp" => op("⊥", "perp"),
        "star" => op("⋆", "star.op"),
        "ast" => op("∗", "ast.op"),
        "dagger" => op("†", "dagger"),
        "therefore" => op("∴", "therefore"),
        "because" => op("∵", "because"),
        "langle" => op("⟨", "chevron.l"),
        "rangle" => op("⟩", "chevron.r"),
        "lfloor" => op("⌊", "floor.l"),
        "rfloor" => op("⌋", "floor.r"),
        "lceil" => op("⌈", "ceil.l"),
        "rceil" => op("⌉", "ceil.r"),
        _ => return None,
    })
}
